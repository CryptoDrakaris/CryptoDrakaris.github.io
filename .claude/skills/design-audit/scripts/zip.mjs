// Minimal ZIP reader for the check scripts (.pptx/.docx, .lottie): central directory,
// stored and deflated entries. No dependencies.
import { inflateRawSync } from 'node:zlib';

/** Map of entry name -> () => Buffer. Throws on a buffer that is not a whole zip. */
export function unzip(buf) {
  let eocd = -1;
  for (let i = buf.length - 22; i >= Math.max(0, buf.length - 65557); i--)
    if (buf.readUInt32LE(i) === 0x06054b50) {
      eocd = i;
      break;
    }
  if (eocd < 0) throw new Error(buf.length >= 4 && buf.readUInt32LE(0) === 0x04034b50 ? 'damaged zip container (truncated or incomplete download)' : 'not a zip container');
  const count = buf.readUInt16LE(eocd + 10);
  let p = buf.readUInt32LE(eocd + 16);
  const entries = new Map();
  for (let n = 0; n < count; n++) {
    if (p + 46 > buf.length || buf.readUInt32LE(p) !== 0x02014b50) break;
    const method = buf.readUInt16LE(p + 10), csize = buf.readUInt32LE(p + 20);
    const nameLen = buf.readUInt16LE(p + 28), extraLen = buf.readUInt16LE(p + 30), commentLen = buf.readUInt16LE(p + 32);
    const local = buf.readUInt32LE(p + 42);
    const name = buf.toString('utf8', p + 46, p + 46 + nameLen);
    entries.set(name, () => {
      const start = local + 30 + buf.readUInt16LE(local + 26) + buf.readUInt16LE(local + 28);
      const data = buf.subarray(start, start + csize);
      return method === 8 ? inflateRawSync(data) : data;
    });
    p += 46 + nameLen + extraLen + commentLen;
  }
  return entries;
}
